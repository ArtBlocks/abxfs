#!/usr/bin/env node
/**
 * Generates `contracts-projects/test/fork/Battery.sol`: every state-changing function on ABX's
 * `SeriesCode` collection, encoded with zero-valued arguments.
 *
 * Why it is generated rather than written: the claim `createOrg` makes — that after it, nobody can
 * change anything — is only as strong as the list of things tested. A hand-written list silently
 * stops covering a mutator ABX adds later. Generating from ABX's own ABI means a new mutator shows
 * up in the diff, and `--check` (run by `test/abx-battery-drift.test.ts`) fails until it does.
 *
 *   node scripts/abx-battery.mjs          rewrite the file
 *   node scripts/abx-battery.mjs --check  exit 1 if the checked-in file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { encodeFunctionData } from "viem";
import { seriesCodeAbi } from "@artblocks/abx-sdk/abi";

const OUT = fileURLToPath(new URL("../../contracts-projects/test/fork/Battery.sol", import.meta.url));

const zero = (t) => {
  if (t.type.endsWith("[]")) return [];
  if (t.type === "tuple") return Object.fromEntries(t.components.map((c) => [c.name, zero(c)]));
  if (t.type === "address") return "0x0000000000000000000000000000000000000000";
  if (t.type === "bool") return false;
  if (t.type === "string") return "";
  if (t.type === "bytes") return "0x";
  if (t.type.startsWith("bytes")) return "0x" + "00".repeat(Number(t.type.slice(5)));
  return 0n;
};

const sigOf = function s(i) {
  return i.type.startsWith("tuple")
    ? "(" + i.components.map(s).join(",") + ")" + i.type.slice(5)
    : i.type;
};

export function generate() {
  const fns = seriesCodeAbi
    .filter((f) => f.type === "function" && f.stateMutability !== "view" && f.stateMutability !== "pure")
    .sort((a, b) => (a.name + a.inputs.length).localeCompare(b.name + b.inputs.length));

  const rows = fns.map((f) => ({
    sig: f.name + "(" + f.inputs.map(sigOf).join(",") + ")",
    data: encodeFunctionData({ abi: [f], functionName: f.name, args: f.inputs.map(zero) }),
  }));

  let out = `// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// GENERATED by packages/sdk/scripts/abx-battery.mjs from @artblocks/abx-sdk. Do not edit by hand:
// run \`pnpm --filter @abxfs/sdk gen:battery\`. Every state-changing selector on ABX's SeriesCode,
// zero-valued arguments.
library Battery {
    function count() internal pure returns (uint256) {
        return ${rows.length};
    }

    function name(uint256 i) internal pure returns (string memory) {
`;
  rows.forEach((r, i) => {
    out += `        ${i ? "else " : ""}if (i == ${i}) return "${r.sig}";\n`;
  });
  out += `        revert();\n    }\n\n    function data(uint256 i) internal pure returns (bytes memory) {\n`;
  rows.forEach((r, i) => {
    out += `        ${i ? "else " : ""}if (i == ${i}) return hex"${r.data.slice(2)}";\n`;
  });
  out += `        revert();\n    }\n}\n`;
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current !== next) {
      console.error(
        "ABX's SeriesCode ABI no longer matches test/fork/Battery.sol.\n" +
          "A mutator was added, removed or changed. Run `pnpm --filter @abxfs/sdk gen:battery`, then read the\n" +
          "diff and decide whether each new function belongs in the fork test's allowlist of caller-scoped no-ops.",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, next);
    console.log("wrote", OUT);
  }
}
